const isoDaysAgo = (days: number, hour = 14, minute = 20) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

const isoInDays = (days: number, hour = 23, minute = 59) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

const dayOffsetKey = (days: number) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return dateKey(d);
};

