import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5, locale: 'zh-CN' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type()==='error' && !m.text().includes('favicon')) errors.push(m.text()); });
await page.goto('http://127.0.0.1:5273/#/city', { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
await page.screenshot({ path: 'screenshots/60-desktop-city.png', fullPage: true });
await page.goto('http://127.0.0.1:5273/#/order/ord_seed_review', { waitUntil: 'networkidle' });
await page.waitForTimeout(700);
await page.screenshot({ path: 'screenshots/61-desktop-order.png', fullPage: true });
await page.goto('http://127.0.0.1:5273/wireframes.html', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
const card = page.locator('.card').filter({ has: page.locator('.card-title h3', { hasText: '订单详情 · 待服务' }) }).first();
await card.scrollIntoViewIfNeeded();
await card.screenshot({ path: 'screenshots/62-wf-order-fixed.png' });
console.log('errors:', errors);
await browser.close();
