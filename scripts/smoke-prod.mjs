import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, locale: 'zh-CN', isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type()==='error' && !m.text().includes('favicon')) errors.push(m.text()); });
await page.goto('http://127.0.0.1:5274/', { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
const deny = page.getByRole('button', { name: '暂不开启' });
if (await deny.count()) await deny.click();
await page.waitForTimeout(400);
console.log('home title:', await page.locator('.hero-copy h2').innerText());
await page.goto('http://127.0.0.1:5274/#/service/curtain', { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
console.log('curtain services:', await page.locator('.service-row').count());
await page.goto('http://127.0.0.1:5274/#/agreements', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
console.log('agreements:', await page.locator('.agreement-item').count());
await page.goto('http://127.0.0.1:5274/wireframes.html', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
console.log('wireframe cards:', await page.locator('.card').count());
console.log('errors:', errors);
await browser.close();
