import { chromium } from 'playwright-core';
const BASE = 'http://127.0.0.1:5281/jingdaojia-cleaning-demo';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1.5, locale: 'zh-CN', isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
const bad = [];
page.on('pageerror', e => errors.push(`PAGEERROR ${e.message}`));
page.on('console', m => { if (m.type() === 'error') errors.push(`CONSOLE ${m.text()}`); });
page.on('response', res => { if (res.status() >= 400) bad.push(`${res.status()} ${res.url()}`); });
await page.goto(`${BASE}/`, { waitUntil: 'networkidle' });
await page.waitForTimeout(900);
const deny = page.getByRole('button', { name: '暂不开启' });
if (await deny.count()) await deny.click();
await page.waitForTimeout(500);
const hero = await page.locator('.hero-copy h2').innerText();
console.log('hero:', hero.replace(/\n/g, ' / '));
console.log('css loaded:', await page.locator('link[rel="stylesheet"]').getAttribute('href'));
await page.goto(`${BASE}/#/service/ac`, { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
console.log('service rows:', await page.locator('.service-row').count());
await page.goto(`${BASE}/#/about`, { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
const wireHref = await page.locator('.about-links a').filter({ hasText: '低保真框线图' }).getAttribute('href');
const pdfHref = await page.locator('.about-links a').filter({ hasText: '框线图 PDF' }).getAttribute('href');
console.log('about wireframes href:', wireHref, '| pdf href:', pdfHref);
await page.goto(`${BASE}/wireframes.html`, { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
console.log('wf cards:', await page.locator('.card').count(), '| wf demo href:', await page.locator('.top-actions a').first().getAttribute('href'), '| wf pdf href:', await page.locator('.top-actions a').nth(1).getAttribute('href'));
await page.goto(`${BASE}/wireframes.pdf`, { waitUntil: 'networkidle' });
console.log('pdf status: loaded');
console.log('errors:', errors.length ? errors : 'none');
console.log('bad responses:', bad.length ? bad : 'none');
await browser.close();
